import http from 'http';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PORT = process.env.PORT || 3001;

const MIME_TYPES = {
    '.html': 'text/html; charset=utf-8',
    '.js': 'application/javascript; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.json': 'application/json; charset=utf-8',
    '.png': 'image/png',
    '.jpg': 'image/jpeg',
    '.svg': 'image/svg+xml',
    '.ico': 'image/x-icon'
};

const server = http.createServer((req, res) => {
    const parsedUrl = new URL(req.url, `http://${req.headers.host}`);
    let pathname = decodeURIComponent(parsedUrl.pathname);

    // Root redirect to examples/twitter/
    if (pathname === '/') {
        res.writeHead(302, { Location: '/examples/twitter/' });
        res.end();
        return;
    }

    // Resolve local file path
    let filePath = path.join(__dirname, pathname);

    // If requesting directory, try index.html
    if (fs.existsSync(filePath) && fs.statSync(filePath).isDirectory()) {
        filePath = path.join(filePath, 'index.html');
    }

    // SPA fallback for Twitter example (only for route paths, not static files with extensions)
    if (!fs.existsSync(filePath)) {
        const ext = path.extname(pathname);
        if (!ext && (pathname.startsWith('/examples/twitter') || pathname.startsWith('/twitter'))) {
            filePath = path.join(__dirname, 'examples', 'twitter', 'index.html');
        }
    }

    if (fs.existsSync(filePath) && fs.statSync(filePath).isFile()) {
        const ext = path.extname(filePath).toLowerCase();
        const contentType = MIME_TYPES[ext] || 'application/octet-stream';
        res.writeHead(200, { 'Content-Type': contentType });
        fs.createReadStream(filePath).pipe(res);
    } else {
        res.writeHead(404, { 'Content-Type': 'text/plain' });
        res.end('404 Not Found');
    }
});

server.listen(PORT, () => {
    console.log(`MelodiJS Dev Server running on http://localhost:${PORT}/examples/twitter/`);
});
